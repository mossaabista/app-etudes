/** "{n} tâche" / "{n} tâches": French treats 0 and 1 as singular, English only 1. */
export function plural(locale: Locale, n: number, one: string, many: string): string {
  const single = locale === "fr" ? n <= 1 : n === 1;
  return fmt(single ? one : many, { n });
}

